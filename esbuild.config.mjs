import esbuild from 'esbuild';
import { builtinModules } from 'node:module';
import process from 'process';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

const stubHighlightJs = {
  name: 'stub-highlight-js',
  setup(build) {
    build.onResolve({ filter: /^highlight\.js\// }, (args) => ({
      path: args.path,
      namespace: 'stub-highlight-js',
    }));
    build.onLoad({ filter: /.*/, namespace: 'stub-highlight-js' }, (args) => ({
      contents: args.path.endsWith('/core')
        ? `const engine = { registerLanguage() {}, getLanguage() {} };
           module.exports = { newInstance: () => engine };
           module.exports.default = module.exports;`
        : 'module.exports = {};',
      loader: 'js',
    }));
  },
};

const context = await esbuild.context({
  banner: {
    js: banner,
  },
  entryPoints: ['src/main.ts'],
  bundle: true,
  plugins: [stubHighlightJs],
  external: [
    'obsidian',
    'electron',
    '@codemirror/autocomplete',
    '@codemirror/collab',
    '@codemirror/commands',
    '@codemirror/language',
    '@codemirror/lint',
    '@codemirror/search',
    '@codemirror/state',
    '@codemirror/view',
    '@lezer/common',
    '@lezer/highlight',
    '@lezer/lr',
    ...builtinModules,
  ],
  format: 'cjs',
  target: 'es2021',
  logLevel: 'info',
  sourcemap: prod ? false : 'inline',
  treeShaking: true,
  outfile: 'main.js',
  minify: prod,
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
